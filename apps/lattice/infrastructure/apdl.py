"""Writes an ANSYS APDL beam-network template for a design. Starting point, not a validated model."""
from ..domain.constants import MATERIALS, TOPOLOGIES
from ..domain.entities import DesignInput
from ..domain.geometry import beams, tile


def build_setup_table(d: DesignInput, expected: dict) -> list[list[str]]:
    mat = MATERIALS[d.material]
    es = max(d.wall_thickness / 3, 0.1)
    return [
        ["Topology", f"{TOPOLOGIES[d.topology]}, angle {d.angle:g} deg"],
        ["Material", f"{mat['label']} (E {mat['E']} MPa, nu {mat['nu']})"],
        ["Cell size L", f"{d.cell_size:g} mm"], ["Wall thickness T", f"{d.wall_thickness:g} mm"],
        ["Lattice", f"4 x 4 cells, about {4 * d.cell_size:.0f} mm wide"],
        ["Element type", "BEAM188, rectangular section"], ["Element size", f"{es:.2f} mm (T / 3)"],
        ["Load", "Top face displaced 10% of height, bottom fixed"],
        ["Twin expects", f"E {expected['E']:.0f} MPa, peak {expected['CPS']:.1f} MPa, nu {expected['NU']:.2f}"],
        ["Layer / nozzle", f"{d.layer_thickness:g} mm / {d.nozzle_temp:g} C (not modelled in a beam model)"],
    ]


def build_script(d: DesignInput) -> str:
    mat = MATERIALS[d.material]
    pts, segs = beams(tile(d.topology, d.angle, 4))
    L = d.cell_size
    ys = [p[1] * L for p in pts]
    xs = [p[0] * L for p in pts]
    y1, height, width = max(ys), max(ys) - min(ys), max(xs) - min(xs)
    es = max(d.wall_thickness / 3, 0.1)
    lines = [
        "! Generated by the lattice digital twin: starting template, check before use",
        "/CLEAR", "/PREP7", f"L_CELL={L:g}", f"T_WALL={d.wall_thickness:g}",
        "DEPTH=10 ! out-of-plane thickness, mm", "EPS_TOP=0.10",
        "ET,1,BEAM188", f"MP,EX,1,{mat['E']}", f"MP,PRXY,1,{mat['nu']}",
        "SECTYPE,1,BEAM,RECT", "SECDATA,T_WALL,DEPTH",
    ]
    lines += [f"K,{i},{p[0] * L:.3f},{y1 - p[1] * L:.3f}" for i, p in enumerate(pts, 1)]
    lines += [f"L,{a},{b}" for a, b in segs]
    lines += [
        "LATT,1,,1,,,,1", f"LESIZE,ALL,{es:.2f}", "LMESH,ALL", "! boundary conditions",
        "NSEL,S,LOC,Y,0", "D,ALL,UY,0", "D,ALL,UX,0",
        f"NSEL,S,LOC,Y,{height:.3f}", f"D,ALL,UY,-EPS_TOP*{height:.3f}", "ALLSEL",
        "/SOLU", "ANTYPE,0", "NLGEOM,ON", "SOLVE", "/POST1",
        "NSEL,S,LOC,Y,0", "FSUM", "*GET,FY,FSUM,0,ITEM,FY", "ALLSEL",
        f"SIG_APP=ABS(FY)/({width:.3f}*DEPTH) ! apparent stress, MPa", "*STATUS,SIG_APP",
    ]
    return "\n".join(lines)
